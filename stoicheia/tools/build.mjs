// Content pipeline: corpus.mjs + lexicon.mjs -> app/corpus.js
// Tokenizes every paragraph, attaches one analysis per lexical token, and refuses to
// write output if any check fails (spec §14 and §20 "Corpus tests").
//
//   node tools/build.mjs

import { writeFileSync } from 'node:fs';
import { WORK, BOOKS, PASSAGES, PLANNED, FIGURES } from '../content/corpus.mjs';
import { LEMMAS, FORMS, describe } from '../content/lexicon.mjs';

const errors = [];
const analyses = [];
const analysisIndex = new Map();

function analysisFor(key) {
  if (analysisIndex.has(key)) return analysisIndex.get(key);
  const entry = FORMS[key];
  if (!entry) return -1;
  const [lemma, code] = entry;
  if (!LEMMAS[lemma]) errors.push(`lemma "${lemma}" (form ${key}) missing from LEMMAS`);
  const d = describe(code);
  analyses.push({ lemma, code, line1: d.line1, line2: d.line2, flat: d.flat, features: d.features });
  analysisIndex.set(key, analyses.length - 1);
  return analyses.length - 1;
}

// A word: letters and combining marks, optional elision mark, optional #variant.
const TOKEN = /([\p{L}\p{M}]+[’ʼ]?)(#\w+)?/gu;
const isLabel = (w) => /^[Α-Ω]+$/u.test(w);

let tokenCount = 0;
function tokenize(source, paragraphId, citation) {
  if (source.normalize('NFC') !== source) errors.push(`${citation}: text is not NFC`);
  let text = '';
  const spans = [];
  let last = 0;
  let t = 0;
  for (const m of source.matchAll(TOKEN)) {
    text += source.slice(last, m.index);
    const surface = m[1];
    const start = text.length;
    text += surface;
    last = m.index + m[0].length;
    if (isLabel(surface)) {
      if (m[2]) errors.push(`${citation}: label ${surface} has a variant marker`);
      spans.push({ s: start, e: text.length, k: 'l' });
      continue;
    }
    const lower = surface.toLowerCase();
    const keys = m[2] ? [surface + m[2], lower + m[2]] : [surface, lower];
    const a = keys.map(analysisFor).find((i) => i >= 0);
    if (a === undefined) {
      errors.push(`${citation}: no analysis for "${keys[0]}"`);
      continue;
    }
    spans.push({ id: `${paragraphId}.t${t++}`, s: start, e: text.length, a });
    tokenCount++;
  }
  text += source.slice(last);
  for (const sp of spans) {
    if (!/^[\p{L}\p{M}]+[’ʼ]?$/u.test(text.slice(sp.s, sp.e))) errors.push(`${citation}: bad range ${sp.s}-${sp.e}`);
  }
  return { text, spans };
}

const firstWords = (text, n = 4) => text.split(/\s+/).slice(0, n).join(' ').replace(/[.,·;]$/, '') + '…';

const passages = PASSAGES.map((p) => {
  const base = `euclid.${p.id}`;
  const paragraphs = [];
  if (p.items) {
    p.items.forEach((src, i) => {
      const citation = `${p.id}.${i + 1}`;
      paragraphs.push({ id: `${base}.p${i}`, role: 'item', cite: citation, ...tokenize(src, `${base}.p${i}`, citation) });
    });
  } else {
    paragraphs.push({ id: `${base}.p0`, role: 'enunciation', ...tokenize(p.enunciation, `${base}.p0`, p.id) });
    p.paragraphs.forEach((src, i) => {
      paragraphs.push({ id: `${base}.p${i + 1}`, role: 'text', ...tokenize(src, `${base}.p${i + 1}`, p.id) });
    });
  }
  if (p.figure && !FIGURES[p.figure]) errors.push(`${p.id}: figure ${p.figure} missing`);
  if (p.kind === 'proposition' && !p.figure) errors.push(`${p.id}: proposition without figure`);
  const range = p.items ? `${p.id}.1–${p.id}.${p.items.length}` : p.id;
  return {
    id: p.id, book: p.book, kind: p.kind, type: p.type || null,
    title: p.title || p.id, greekTitle: p.greekTitle, range, planned: p.planned || null,
    figure: p.figure || null, firstWords: firstWords(paragraphs[0].text), paragraphs,
  };
});

const ids = passages.map((p) => p.id);
if (new Set(ids).size !== ids.length) errors.push('duplicate passage citation');

if (errors.length) {
  console.error(`Build failed with ${errors.length} problem(s):\n  ` + errors.join('\n  '));
  process.exit(1);
}

const out = {
  version: 1,
  work: WORK, books: BOOKS, planned: PLANNED, figures: FIGURES, passages,
  lemmas: LEMMAS, analyses,
};
const target = new URL('../app/corpus.js', import.meta.url);
writeFileSync(target, `// Generated by tools/build.mjs. Do not edit by hand.\nwindow.STOICHEIA = ${JSON.stringify(out)};\n`);
console.log(`OK: ${passages.length} passages, ${tokenCount} analysed tokens, ${analyses.length} distinct analyses, ${Object.keys(LEMMAS).length} lemmas`);
